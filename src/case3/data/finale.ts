export interface Verdict3 { verdict: 'again' | 'close' | 'solved'; score: number; headline: string; message: string; parts: { key: string; label: string; ok: boolean; note: string }[] }

export function judge3(a: { ans: Record<string, string>; evidence: string[]; rejected: string[]; summary: string }): Verdict3 {
  const parts: Verdict3['parts'] = [];
  let score = 0;
  const notes: Record<string, [string, string]> = {
    cause: ['Причина установлена.', 'Причина не согласуется с результатами исследований: сопоставьте профиль веществ и способ введения.'],
    who: ['Лицо названо обоснованно.', 'Названное лицо не согласуется с присутствием, физическими следами и источником вещества.'],
    others: ['Структура других смертей понята.', 'Другие смерти объяснены не так: проверьте профили, документы и присутствие.'],
    nurse: ['Роль медсестры оценена верно.', 'Роль медсестры определена неточно: отделите нарушения от причины смерти.'],
    doctor: ['Роль врача оценена верно.', 'Роль врача определена неточно: сопоставьте документы согласий и профили.'],
    rakh: ['Роль санитара оценена верно.', 'Роль санитара определена неточно: проверьте время и обстоятельства.'],
    money: ['Роль ренты оценена верно.', 'Роль ренты определена неточно: проверьте базовую долю договоров.'],
    motive: ['Мотив соответствует материалам.', 'Мотив не подтверждается материалами дела.'],
  };
  for (const q of QUESTIONS3) {
    const ok = a.ans[q.id] === ANS[q.id];
    if (ok) score += W[q.id];
    parts.push({ key: q.id, label: q.title, ok, note: notes[q.id][ok ? 0 : 1] });
  }
  const picked = new Set(a.evidence);
  const covered = Object.values(KEY_GROUPS).filter((g) => g.some((id) => picked.has(id))).length;
  const ev = Math.min(10, covered * 3 - (a.evidence.length > 9 ? 1 : 0));
  score += Math.max(0, ev);
  parts.push({ key: 'evidence', label: 'Доказательства', ok: covered >= 3, note: covered >= 3 ? 'Доказательная база охватывает метод, присутствие и закономерность.' : 'Не хватает доказательств по одному из звеньев: способ, присутствие, закономерность, подтверждение.' });
  const wrongRej = ASSUMPTIONS3.filter((x) => x.wrong && a.rejected.includes(x.id)).length;
  const falseRej = ASSUMPTIONS3.filter((x) => !x.wrong && a.rejected.includes(x.id)).length;
  const as = Math.max(0, Math.min(10, wrongRej * 2 - falseRej * 2));
  score += as;
  parts.push({ key: 'assump', label: 'Пересмотр первоначальных версий', ok: as >= 8, note: as >= 8 ? 'Ложные версии отброшены верно.' : falseRej ? 'Среди отброшенных версий есть подтверждающиеся.' : 'Не все ложные предположения отброшены.' });
  const verdict: Verdict3['verdict'] = score >= 80 ? 'solved' : score >= 55 ? 'close' : 'again';
  return {
    verdict, score,
    headline: verdict === 'solved' ? 'Версия принята' : verdict === 'close' ? 'Версия близка, но есть слабые звенья' : 'Версия не подтверждается',
    message: verdict === 'solved' ? 'Реконструкция согласуется с материалами дела. Дело можно направлять в суд.' : verdict === 'close' ? 'Основа версии обоснована, но отдельные утверждения не подтверждены. Прогресс сохранён: уточните и подайте снова.' : 'Версия не опирается на достаточные доказательства. Продолжайте расследование.',
    parts,
  };
}

