export interface Verdict {
  verdict: 'again' | 'close' | 'solved';
  score: number;
  headline: string;
  message: string;
  parts: { key: string; label: string; ok: boolean; note: string }[];
}

export function judge(a: { ans: Record<string, string>; evidence: string[]; rejected: string[]; summary: string }): Verdict {
  const parts: Verdict['parts'] = [];
  const w: Record<string, number> = { exit: 10, helper: 8, msg1: 10, msg2: 10, culprit: 18, link: 12, where: 10 };
  let score = 0;
  const notes: Record<string, [string, string]> = {
    exit: ['Способ ухода установлен.', 'Способ ухода не подтверждается следами и записями камер.'],
    helper: ['Помощник назван верно.', 'Помощник указан неверно: сопоставьте запись камер и доступ к аппаратуре.'],
    msg1: ['Происхождение сообщений в 03:12 установлено.', 'Ночные сообщения объяснены не так: обратите внимание на то, когда они были созданы.'],
    msg2: ['Подделка вычислена верно.', 'Происхождение нового сообщения объяснено не так: сверьте метаданные и шумовой портрет.'],
    culprit: ['Лицо, стоящее за подменой голоса, названо верно.', 'Выбранное лицо не согласуется с доступом, записями и ложью свидетелей.'],
    link: ['Связь трёх дел и ночи Алины установлена.', 'Связь описана иначе, чем подтверждают архивные записи и шумовые портреты.'],
    where: ['Место определено верно.', 'Место не подтверждается журналами школы, ключами и показаниями.'],
  };
  for (const q of QUESTIONS) {
    const ok = a.ans[q.id] === ANSWERS[q.id];
    if (ok) score += w[q.id];
    parts.push({ key: q.id, label: q.title, ok, note: notes[q.id][ok ? 0 : 1] });
  }
  const picked = new Set(a.evidence);
  const cats = Object.entries(KEY_EVIDENCE).map(([k, v]) => [k, v.filter((id) => picked.has(id)).length] as const);
  const covered = cats.filter(([, n]) => n >= 1).length;
  const evScore = Math.min(12, covered * 3);
  score += evScore;
  parts.push({
    key: 'evidence', label: 'Доказательная база', ok: covered >= 3,
    note: covered >= 3 ? 'Доказательства покрывают основные звенья версии.' : 'Доказательств недостаточно: не показано, ' + [
      !cats.find(([k, n]) => k === 'how' && n) ? 'как она ушла' : '',
      !cats.find(([k, n]) => k === 'plan' && n) ? 'что уход был подготовлен' : '',
      !cats.find(([k, n]) => k === 'culprit' && n) ? 'кто подменяет голоса' : '',
      !cats.find(([k, n]) => k === 'where' && n) ? 'где она находится' : '',
    ].filter(Boolean).join('; ') + '.',
  });
  const wrongRejected = WRONG_ASSUMPTIONS.filter((x) => x.wrong && a.rejected.includes(x.id)).length;
  const falseReject = WRONG_ASSUMPTIONS.filter((x) => !x.wrong && a.rejected.includes(x.id)).length;
  const rScore = Math.max(0, Math.min(10, Math.round((wrongRejected / 6) * 10) - falseReject * 2));
  score += rScore;
  parts.push({
    key: 'assumptions', label: 'Пересмотр первоначальных версий', ok: rScore >= 7,
    note: rScore >= 7 ? 'Ложные версии отброшены верно.' : falseReject ? 'Среди отброшенных версий есть те, что подтверждаются.' : 'Не все ложные предположения отброшены.',
  });
  if (a.summary.trim().length > 60) score += 10;
  parts.push({ key: 'summary', label: 'Итоговое изложение', ok: a.summary.trim().length > 60, note: a.summary.trim().length > 60 ? 'Реконструкция изложена.' : 'Изложите версию своими словами: что произошло и почему.' });

  score = Math.round((score * 100) / 110);
  const verdict: Verdict['verdict'] = score >= 85 ? 'solved' : score >= 55 ? 'close' : 'again';
  return {
    verdict, score,
    headline: verdict === 'solved' ? 'Реконструкция принята' : verdict === 'close' ? 'Версия близка, но не завершена' : 'Версию нужно переработать',
    message:
      verdict === 'solved'
        ? 'Совокупность выводов и доказательств описывает события без существенных противоречий. Дело закрыто.'
        : verdict === 'close'
          ? 'Основа версии верна, но отдельные звенья не подтверждаются. Вернитесь к отмеченным разделам, уточните и подайте реконструкцию снова — прогресс сохранён.'
          : 'Версия слишком расходится с материалами. Продолжайте расследование, используйте подсказки и повторите попытку.',
    parts,
  };
}

