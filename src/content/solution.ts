export function evaluate(a: Accusation): EvalResult {
  const sections: SectionResult[] = [];
  const suspectOk = a.suspect === KILLER;

  if (!suspectOk) {
    return {
      verdict: 'wrong',
      headline: 'Обвинение не принято',
      message:
        WRONG_SUSPECT[a.suspect] ??
        'Выдвинутое обвинение не подтверждается материалами дела. Вернитесь к хронологии и сверьте показания с объективными данными.',
      sections: [
        { key: 'suspect', label: 'Подозреваемый', ok: false, note: 'Версия не выдерживает проверки.' },
      ],
    };
  }

  const methodOk = a.method === 'push';
  const momentOk = a.moment === 't0115';
  const entryOk = a.entry === 'e3';
  const motiveOk = a.motive === 'invest';

  const picked = new Set(a.evidence);
  const keyCount = a.evidence.filter((e) => KEY_ALL.has(e)).length;
  const hasPresence = KEY_PRESENCE.some((k) => picked.has(k));
  const hasTime = KEY_TIME.some((k) => picked.has(k));
  const hasMotive = KEY_MOTIVE.some((k) => picked.has(k));
  const evidenceOk = keyCount >= 4 && hasPresence && hasTime && hasMotive;

  const lieSet = new Set(a.lies);
  const correctLies = FALSE_CLAIMS.filter((c) => lieSet.has(c)).length;
  const wrongLies = a.lies.filter((c) => !FALSE_CLAIMS.includes(c)).length;
  const liesOk = lieSet.has(CORE_CLAIM) && correctLies >= 3 && wrongLies <= 1;

  sections.push({ key: 'suspect', label: 'Подозреваемый', ok: true, note: 'Личность установлена верно.' });
  sections.push({
    key: 'method',
    label: 'Способ',
    ok: methodOk,
    note: methodOk
      ? 'Способ совершения преступления установлен.'
      : 'Описанный способ не согласуется с заключением экспертизы и данными об окружающей обстановке.',
  });
  sections.push({
    key: 'moment',
    label: 'Время',
    ok: momentOk,
    note: momentOk
      ? 'Момент нападения указан верно.'
      : 'Указанное время не подтверждается данными, фиксирующими момент падения.',
  });
  sections.push({
    key: 'entry',
    label: 'Проникновение',
    ok: entryOk,
    note: entryOk
      ? 'Путь на место происшествия указан верно.'
      : 'Указанный путь не согласуется с данными о воротах, следах и снеге.',
  });
  sections.push({
    key: 'motive',
    label: 'Мотив',
    ok: motiveOk,
    note: motiveOk
      ? 'Мотив подтверждается документами.'
      : 'Названный мотив не подтверждается финансовыми и договорными документами.',
  });

  const evNotes: string[] = [];
  if (keyCount < 4) evNotes.push('приведено слишком мало ключевых доказательств');
  if (!hasPresence) evNotes.push('нет доказательств присутствия подозреваемого на месте');
  if (!hasTime) evNotes.push('нет доказательств, фиксирующих время события');
  if (!hasMotive) evNotes.push('нет доказательств мотива');
  sections.push({
    key: 'evidence',
    label: 'Доказательства',
    ok: evidenceOk,
    note: evidenceOk ? 'Доказательная база достаточна.' : 'Недостаточно: ' + evNotes.join('; ') + '.',
  });
  sections.push({
    key: 'lies',
    label: 'Ложные показания',
    ok: liesOk,
    note: liesOk
      ? 'Ключевая ложь установлена верно.'
      : !lieSet.has(CORE_CLAIM)
        ? 'Не отмечено ложное показание, на котором держится алиби подозреваемого.'
        : wrongLies > 1
          ? 'Среди отмеченных показаний есть правдивые.'
          : 'Отмечено слишком мало действительно ложных показаний.',
  });

  const okCount = [methodOk, momentOk, entryOk, motiveOk].filter(Boolean).length;
  const solved = okCount >= 3 && methodOk && motiveOk && evidenceOk && liesOk;

  if (solved) {
    return {
      verdict: 'solved',
      headline: 'Дело раскрыто',
      message:
        'Обвинение принято. Совокупность доказательств устанавливает событие преступления, его способ, мотив и ложность алиби подозреваемого.',
      sections,
    };
  }
  return {
    verdict: 'partial',
    headline: 'Обвинение принято частично',
    message:
      'Личность подозреваемого названа верно, но версия в целом не может быть направлена в суд. Отдельные элементы не подтверждаются. Дополните расследование и подайте обвинение снова.',
    sections,
  };
}

