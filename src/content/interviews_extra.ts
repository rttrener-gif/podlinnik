import { INTERVIEW_BY_PERSON } from './interviews';
import type { Confront, Question } from '../types';

// Углубление допросов: дополнительные вопросы и контекстные реакции на улики.
// Реакция допрашиваемого меняется, когда у следователя появляются новые сведения.

function addQ(person: string, qs: Question[]) {
  INTERVIEW_BY_PERSON[person].questions.push(...qs);
}
function addC(person: string, doc: string, c: Confront) {
  const iv = INTERVIEW_BY_PERSON[person];
  const cur = iv.confront[doc];
  if (cur) {
    cur.variants = [...(cur.variants ?? []), ...(c.variants ?? [])];
  } else {
    iv.confront[doc] = c;
  }
}

